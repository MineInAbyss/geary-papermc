package com.mineinabyss.geary.papermc.features.resourcepacks

import com.mineinabyss.jsonschema.dsl.SchemaContext
import com.mineinabyss.jsonschema.dsl.SchemaProperty
import com.mineinabyss.jsonschema.dsl.SchemaPropertyBuilder
import com.mineinabyss.jsonschema.dsl.SchemaType

/**
 * Schema for item model definitions, mirroring what [ItemModelResolver] expands and creative reads.
 * Keys are written in camelCase and converted to snake_case, so multi word keys are accepted in either form.
 *
 * Model types are picked with if/then on `type` rather than anyOf, so editors report the error in the branch that applies
 * instead of guessing which of the types was meant
 */
internal object ItemModelSchema {
    private const val MODEL = "geary:item_model_definition"
    private const val MODEL_REF = "#/\$defs/$MODEL"

    private val CUSTOM_TYPES = listOf("texture", "bbmodel", "reference")
    private val VANILLA_TYPES = listOf("model", "composite", "condition", "select", "range_dispatch", "special", "empty", "bundle/selected_item")

    context(context: SchemaContext)
    fun SchemaProperty.itemModel() {
        ref = context.definition(MODEL, null) {
            description = "An item model, or the key of an existing model"
            type = null
            ifThen(
                condition = { type = SchemaType.STRING },
                then = { type = SchemaType.STRING },
                otherwise = { allOf(listOf(typeProperty) + modelTypes) },
            )
        }
    }

    /** The item model component, a model written inline or under `model` alongside a generated model's `key` */
    context(context: SchemaContext)
    fun SchemaProperty.itemModelComponent() {
        type = null
        ifThen(
            condition = {
                required += "model"
                propertyNames { enum += listOf("model", "key") }
            },
            then = {
                property("model") { itemModel() }
                key("key", "Key to register the generated model under")
            },
            otherwise = { itemModel() },
        )
    }

    private val typeProperty: SchemaPropertyBuilder = {
        property("type") {
            type = SchemaType.STRING
            enum += CUSTOM_TYPES + VANILLA_TYPES.flatMap { listOf(it, "minecraft:$it") }
        }
    }

    private val modelTypes: List<SchemaPropertyBuilder> = listOf(
        // Our own types may leave out `type`, which is then picked from the fields that are present
        inferredType("texture") {
            key("texture", "Texture to generate a flat item model from")
            camelOrSnake("parentModel") {
                type = SchemaType.STRING
                description = "Model the generated one inherits from, minecraft:item/generated by default"
            }
            tints()
        },
        inferredType("bbmodel") {
            key("bbmodel", "Blockbench model to generate the item model from")
            tints()
        },
        modelType("reference", vanilla = false) {
            key("model", "Model to use, the prefab's own model when left out")
            tints()
        },
        modelType("model") {
            required += "model"
            key("model", "Model to use")
            tints()
        },
        modelType("composite") {
            required += "models"
            property("models") { type = SchemaType.ARRAY; items { ref = MODEL_REF } }
        },
        modelType("condition") {
            allOf(
                {
                    required += "property"
                    property("property") { suggest(CONDITION_PROPERTIES) }
                    camelOrSnake("onTrue") { ref = MODEL_REF }
                    camelOrSnake("onFalse") { ref = MODEL_REF }
                },
                { requireCamelOrSnake("onTrue") },
                { requireCamelOrSnake("onFalse") },
            )
        },
        modelType("select") {
            required += listOf("property", "cases")
            property("property") { suggest(SELECT_PROPERTIES) }
            property("cases") { type = SchemaType.ARRAY; items { entry("when") { whenValue() } } }
            property("fallback") { ref = MODEL_REF }
        },
        modelType("range_dispatch") {
            required += listOf("property", "entries")
            property("property") { suggest(RANGE_PROPERTIES) }
            property("scale") { type = SchemaType.NUMBER }
            property("entries") { type = SchemaType.ARRAY; items { entry("threshold") { type = SchemaType.NUMBER } } }
            property("fallback") { ref = MODEL_REF }
        },
        modelType("special") {
            required += "model"
            property("model") {
                required += "type"
                property("type") { suggest(SPECIAL_MODELS) }
            }
            key("base", "Model providing particles and display transforms")
        },
    )

    private fun modelType(name: String, vanilla: Boolean = true, fields: SchemaPropertyBuilder): SchemaPropertyBuilder = {
        type = null
        ifThen(
            condition = {
                required += "type"
                property("type") { enum += if (vanilla) listOf(name, "minecraft:$name") else listOf(name) }
            },
            then = fields,
        )
    }

    // Applies when `type` names this type, or when it's left out and the field this type is named after is present
    private fun inferredType(name: String, fields: SchemaPropertyBuilder): SchemaPropertyBuilder = {
        type = null
        ifThen(
            condition = {
                anyOf(
                    { required += "type"; property("type") { enum += name } },
                    { required += name; property("type") { enum += name } },
                )
            },
            then = {
                required += name
                fields()
            },
        )
    }

    private fun snakeCase(name: String) = name.replace(Regex("([a-z0-9])([A-Z])"), "$1_$2").lowercase()

    private fun SchemaProperty.camelOrSnake(name: String, init: SchemaPropertyBuilder) {
        property(name, init = init)
        property(snakeCase(name), init = init)
    }

    private fun SchemaProperty.requireCamelOrSnake(name: String) = anyOf(
        { required += name },
        { required += snakeCase(name) },
    )

    private fun SchemaProperty.key(name: String, description: String) = property(name) {
        type = SchemaType.STRING
        this.description = description
    }

    private fun SchemaProperty.tints() = property("tints") {
        description = "A single tint or a list of them"
        anyOf(
            { tint() },
            { type = SchemaType.ARRAY; items { tint() } },
        )
    }

    private fun SchemaProperty.tint() {
        required += "type"
        property("type") { suggest(TINTS) }
    }

    // Holding only `model` besides the matching field nests the model, anything else is the model written inline
    private fun SchemaProperty.entry(field: String, value: SchemaPropertyBuilder) = ifThen(
        condition = {
            required += listOf(field, "model")
            propertyNames { enum += listOf(field, "model") }
        },
        then = {
            property(field, init = value)
            property("model") { ref = MODEL_REF }
        },
        otherwise = {
            allOf(
                { required += field; property(field, init = value) },
                { ref = MODEL_REF },
            )
        },
    )

    private fun SchemaProperty.whenValue() {
        description = "Value or list of values this case matches"
        type = null
    }

    // Vanilla accepts anything registered, so known values are suggested without rejecting others
    private fun SchemaProperty.suggest(values: List<String>) = anyOf(
        { type = SchemaType.STRING; enum += values.flatMap { listOf(it, "minecraft:$it") } },
        { type = SchemaType.STRING },
    )

    private val CONDITION_PROPERTIES = listOf(
        "broken", "bundle/has_selected_item", "carried", "component", "custom_model_data", "damaged",
        "extended_view", "fishing_rod/cast", "has_component", "keybind_down", "selected", "using_item", "view_entity",
    )
    private val SELECT_PROPERTIES = listOf(
        "block_state", "charge_type", "component", "context_dimension", "context_entity_type", "custom_model_data",
        "display_context", "local_time", "main_hand", "trim_material",
    )
    private val RANGE_PROPERTIES = listOf(
        "bundle/fullness", "compass", "cooldown", "count", "crossbow/pull", "custom_model_data", "damage",
        "time", "use_cycle", "use_duration",
    )
    private val SPECIAL_MODELS = listOf(
        "banner", "bed", "chest", "conduit", "copper_golem_statue", "decorated_pot", "hanging_sign", "head",
        "player_head", "shield", "shulker_box", "standing_sign", "trident",
    )
    private val TINTS = listOf("constant", "custom_model_data", "dye", "firework", "grass", "map_color", "potion", "team")
}
